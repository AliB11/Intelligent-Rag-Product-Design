/** A single mode (طرح) of the synthesized multi-mode banking product. */
export interface ModeSpec {
  id: string;
  nameFa: string;
  nameEn: string;
  archetype: ModeArchetype;
  contract: ContractType;
  /** w_m — share of the target resource volume. */
  weight: number;
  /** D_m — attracted deposit volume in Rial. */
  depositVolumeRial: number;
  /** r_d,m — nominal deposit / expected-return rate. */
  depositRate: number;
  /** RR_m — statutory reserve ratio. */
  statutoryReserve: number;
  /** LR_m — vault & ATM liquidity deduction. */
  liquidityDeduction: number;
  /** theta_OpEx. */
  opexRatio: number;
  /** PD_m and LGD_m of the loan book generated by this mode. */
  pd: number;
  lgd: number;
  /** tau_d,m — deposit sleep period (months of average balance). */
  sleepMonths: number;
  /** alpha_m — loan multiplier over the weighted average balance. */
  loanMultiplier: number;
  /** tau_l,m — repayment tenor in months. */
  tenorMonths: number;
  /** r_l,m — Morabaha profit rate or Qarz-ol-Hasanah commission. */
  loanRate: number;
  /** beta_m — contractually blocked fraction (مسدودی هوشمند). */
  blockedRatio: number;
  /** omega_m — waiting queue period after the sleep period (months). */
  waitingMonths: number;
  /** gamma_m — closed-loop retention fraction (merchant/supplier settlement). */
  closedLoopRetention: number;
  /** delta_m — mean unblocked withdrawal fraction at disbursement. */
  withdrawalFractionMean: number;
  /** kappa_source — source weight multiplier of the point engine. */
  sourceKappa: number;
  /** Non-joint origination / service fee rate charged once per facility. */
  feeIncomeRate: number;
  /** L_max,m — per-customer ceiling in Toman. */
  capToman: number;
  /** Average facility ticket in Toman. */
  avgTicketToman: number;
  /** Customer adoption score contribution (0..1). */
  adoptionScore: number;
  blockRelease: BlockReleaseSchedule;
  /** Months over which the cohort ramp reaches full inflow. */
  cohortRampMonths: number;
  /** Persona monthly net income (Toman) used by the affordability test. */
  personaIncomeToman: number;
  /** Derived metrics. */
  costOfFunds: number;
  expectedLoss: number;
  freeResourcesRial: number;
  loanBookRial: number;
  monthlyInstallmentToman: number;
  installmentToIncome: number;
  npvBankRial: number;
  customers: number;
}

